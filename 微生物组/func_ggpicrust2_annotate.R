# Function to generate an empty plot
empty_plot <- function(text) {
  p <- ggplot() +
    annotate("text", x = 4, y = 25, size=8, label = text) +
    theme_void() +
    theme(panel.background = element_rect(fill = 'white'))
  return(p)
}

# Function to perform differential analysis on KEGG KO
ggpicrust2 <- function(abundance_df, meta_df, group_list, database, keggDB) {

  # Set parameters based on database type (KEGG, EC, MetaCyc)
  ko_to_kegg_flag <- FALSE
  if (database == "KEGG") {
    abundance <- ko2kegg_abundance(data=abundance_df)
    type <- "KO"
    ko_to_kegg_flag <- TRUE
    order_val <- "pathway_class"
    x_lab_val <- "pathway_name"
    columns <- c("feature", "log_2_fold_change", "p_values", "p_adjust",
                 "pathway_name", "pathway_class", "pathway_map")
  } else if (database == "EC") {
    abundance <- abundance_df %>%
      column_to_rownames("ec")
    type <- "EC"
    order_val <- "group"
    x_lab_val <- "description"
    columns <- c("feature", "log_2_fold_change", "p_values", "p_adjust", "description")
  } else if (database == "MetaCyc") {
    abundance <- abundance_df %>%
      column_to_rownames("pathway")
    type <- "MetaCyc"
    order_val <- "group"
    x_lab_val <- "description"
    columns <- c("feature", "log_2_fold_change", "p_values", "p_adjust", "description")
  }

  # Perform Differential abundance(DA) analysis
  daa_results_df <- pathway_daa(
    abundance = abundance,
    metadata = meta_df,
    group = "group",
    daa_method = "LinDA",
    select = NULL,
    reference = group_list[2]
  )

  # Check if there is any significant results (p_adjust<0.05)
  if (nrow(daa_results_df[daa_results_df$p_adjust < 0.05,]) == 0) {
    # If not, output empty plot
    plot_text <- "No statistically significant biomarkers found!"
    p <- empty_plot(text=plot_text)

    # If not, output empty table
    test_table_out <- data.frame(matrix(nrow = 0, ncol = length(columns)))
    colnames(test_table_out) <- columns

    abundance_out <- abundance[order(row.names(abundance), decreasing=FALSE), ]
    return(list("p"=p, "abundance_df"=abundance_out, "test_df"=test_table_out))
  } else {
    daa_results_df <- daa_results_df[daa_results_df$p_adjust < 0.05,]
    # More than 30 items will cause an error in pathway_errorbar thus select top30
    if (nrow(daa_results_df) > 30) {
      daa_results_df_top30 <- daa_results_df[order(daa_results_df$p_adjust),][1:30,]
    } else {
      daa_results_df_top30 <- daa_results_df
    }

    # Database annotation
    if (database == "KEGG") {
      # Use KEGG pathway annotation database to annotate KEGG since pathway_annotation() might meet network issue with pathway = "KO"
      kegg_db <- read.table(keggDB, header=T, check.names=F, row.names=NULL, sep="\t") %>%
        dplyr::mutate(pathway_name = pathway_level3, pathway_map = pathway_level3) %>%
        dplyr::mutate(pathway_class = paste0(pathway_level1, "; ", pathway_level2)) %>%
        dplyr::select(pathway_ID, pathway_name, pathway_class, pathway_map)
      daa_annotated_results_df <- merge(daa_results_df_top30, kegg_db, by.x="feature", by.y="pathway_ID", all.x=TRUE)
    } else {
      # Use pathway_annotation() function to annotate EC and MetaCyc
      daa_annotated_results_df <- pathway_annotation(
        pathway = type,
        daa_results_df = daa_results_df_top30,
        ko_to_kegg = ko_to_kegg_flag
      )
    }

    # Generate ggpicrust2 errorbar plot
    p <- pathway_errorbar(
      abundance = abundance,
      daa_results_df = daa_annotated_results_df %>% dplyr::mutate(p_adjust=round(p_adjust,3)),
      Group = meta_df$group,
      p_values_threshold = 0.05,
      order = order_val,
      select = NULL,
      ko_to_kegg = ko_to_kegg_flag,
      p_value_bar = TRUE,
      colors = NULL,
      x_lab = x_lab_val
    )

    # Prepare output items
    abundance_out <- abundance[order(row.names(abundance), decreasing=FALSE), ]
    test_table_out <- p$data %>%
      dplyr::mutate(p_values = as.numeric(p_values)) %>%
      dplyr::select(columns) %>%
      dplyr::arrange(p_values)
    abundance_out <- abundance_out %>%
      rownames_to_column("feature")

    # Output
    return(list("p"=p, "abundance_df"=abundance_out, "test_df"=test_table_out))
  }
}

