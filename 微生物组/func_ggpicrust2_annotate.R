# Read abundance table
abundance_df <- read_delim(
  opts$input,
  delim = "\t",
  col_names = TRUE,
  trim_ws = TRUE
)

# Database annotation
if (opts$database == "KEGG") {
  abundance <- ko2kegg_abundance(data=abundance_df) %>%
    rownames_to_column("feature")
  # Use KEGG pathway annotation database to annotate KEGG since pathway_annotation() might meet network issue with pathway = "KO"
  kegg_db <- read.table(opts$keggDB, header=T, check.names=F, row.names=NULL, sep="\t") %>%
    dplyr::mutate(pathway_name = pathway_level3, pathway_map = pathway_level3) %>%
    dplyr::mutate(pathway_class = paste0(pathway_level1, "; ", pathway_level2)) %>%
    dplyr::select(pathway_ID, pathway_name, pathway_class, pathway_map)
  abundance_annotated <- merge(abundance, kegg_db, by.x="feature", by.y="pathway_ID", all.x=TRUE)
} else if (opts$database == "EC") {
  abundance <- abundance_df %>%
      rename(feature=ec)
  # Use pathway_annotation() function to annotate EC and MetaCyc
  abundance_annotated <- pathway_annotation(
    pathway = "EC",
    daa_results_df = abundance,
    ko_to_kegg = FALSE
  )
} else if (opts$database == "MetaCyc") {
  abundance <- abundance_df %>%
      rename(feature=pathway)
  # Use pathway_annotation() function to annotate EC and MetaCyc
  abundance_annotated <- pathway_annotation(
    pathway = "MetaCyc",
    daa_results_df = abundance,
    ko_to_kegg = FALSE
  )
}

# Output
write.table( abundance_annotated,
            file=file.path(opts$outdir, glue("all.{opts$database}.abundance.xls")),
            row.names = FALSE,
            col.names = TRUE,
            quote = FALSE,
            sep = "\t")
