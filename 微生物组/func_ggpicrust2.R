# Convert contrast to group list
group_list <- unlist(strsplit(opts$contrast, "-vs-"))

# Read metadata
meta_df <- read.table(opts$meta, header=T, check.names=F, row.names=NULL, sep="\t") %>%
  dplyr::rename("sample" = opts$sample, "group" = opts$group) %>%
  dplyr::select(sample, group) %>%
  dplyr::filter(group %in% group_list)

# Read abundance table
abundance_df <- read_delim(
  opts$input,
  delim = "\t",
  col_names = TRUE,
  trim_ws = TRUE
)
abundance_df <- abundance_df %>%
  dplyr::select(colnames(abundance_df)[1], meta_df$sample)

# Perform differential analysis using ggpicrust2
db_name <- opts$database
if (db_name == "KEGG") {
  output_list <- ggpicrust2(abundance_df=abundance_df, meta_df=meta_df, group_list=group_list, database=db_name, keggDB=opts$keggDB)
} else {
  output_list <- ggpicrust2(abundance_df=abundance_df, meta_df=meta_df, group_list=group_list, database=db_name)
}

# Output
output_abundance_df <- output_list$abundance_df
output_test_df <- output_list$test_df
output_p <- output_list$p

write.table(output_abundance_df,
            file=file.path(opts$outdir, glue("{opts$contrast}.{db_name}.abundance.xls")),
            row.names = FALSE,
            col.names = TRUE,
            quote = FALSE,
            sep = "\t")

write.table(output_test_df,
            file=file.path(opts$outdir, glue("{opts$contrast}.{db_name}.significant.xls")),
            row.names = FALSE,
            col.names = TRUE,
            quote = FALSE,
            sep = "\t")

pdf(glue("{opts$outdir}/{opts$contrast}.{db_name}.significant.pdf"), height=10, width=20)
output_p
