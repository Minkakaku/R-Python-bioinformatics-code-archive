# Function to generate an empty plot
empty_plot <- function(text) {
  p <- ggplot() +
    annotate("text", x = 4, y = 25, size=8, label = text) +
    theme_void() +
    theme(panel.background = element_rect(fill = 'white'))
  return(p)
}

# Function to perform differential analysis on KEGG KO
ggpicrust2 <- function(abundance_df, meta_df, group_list, database, keggDB) {

  # Set parameters based on database type (KEGG, EC, MetaCyc)
  ko_to_kegg_flag <- FALSE
  if (database == "KEGG") {
    abundance <- ko2kegg_abundance(data=abundance_df)
    type <- "KO"
    ko_to_kegg_flag <- TRUE
    order_val <- "pathway_class"
    x_lab_val <- "pathway_name"
    columns <- c("feature", "log_2_fold_change", "p_values", "p_adjust",
                 "pathway_name", "pathway_class", "pathway_map")
  } else if (database == "EC") {
    abundance <- abundance_df %>%
      column_to_rownames("ec")
    type <- "EC"
    order_val <- "group"
    x_lab_val <- "description"
    columns <- c("feature", "log_2_fold_change", "p_values", "p_adjust", "description")
  } else if (database == "MetaCyc") {
    abundance <- abundance_df %>%
      column_to_rownames("pathway")
    type <- "MetaCyc"
    order_val <- "group"
    x_lab_val <- "description"
    columns <- c("feature", "log_2_fold_change", "p_values", "p_adjust", "description")
  }

  # Remove features with all zero counts
  abundance <- abundance[rowSums(abundance) != 0,]

  # Perform Differential abundance(DA) analysis
  daa_results_df <- pathway_daa(
    abundance = abundance,
    metadata = meta_df,
    group = "group",
    daa_method = "LinDA",
    select = NULL,
    reference = group_list[2]
  )

  # # Check if there is any significant results (p_adjust<0.05)
  # if (nrow(daa_results_df[daa_results_df$p_adjust < 0.05,]) == 0) {
  #   # If not, use the items with top30 p-values for plotting
  #   # More than 30 items will cause an error in pathway_errorbar thus select top30
  #   if (nrow(daa_results_df) > 30) {
  #     daa_results_df_top30 <- daa_results_df[order(daa_results_df$p_values),][1:30,]
  #   } else {
  #     daa_results_df_top30 <- daa_results_df[order(daa_results_df$p_values),]
  #   }
  # } else {
  #   # Check if number of significant item equals 1
  #   if (nrow(daa_results_df[daa_results_df$p_adjust < 0.05,]) == 1) {
  #     # Manually select Top2 since only one item will cause an error in pathway_errorbar()
  #     daa_results_df_top30 <- daa_results_df[order(daa_results_df$p_values),][order(daa_results_df$p_adjust),][1:2,]
  #   } else {
  #     daa_results_df_tmp <- daa_results_df[daa_results_df$p_adjust < 0.05,]
  #     # More than 30 items will cause an error in pathway_errorbar thus select top30
  #     if (nrow(daa_results_df_tmp) > 30) {
  #       daa_results_df_top30 <- daa_results_df_tmp[order(daa_results_df_tmp$p_adjust),][1:30,]
  #     } else {
  #       daa_results_df_top30 <- daa_results_df_tmp[order(daa_results_df_tmp$p_adjust),]
  #     }
  #   }
  # }

  # Select features with top30 p_values to be present in barplot
  if (nrow(daa_results_df) > 30) {
      daa_results_df_top30 <- daa_results_df[order(daa_results_df$p_values),][1:30,]
  } else {
      daa_results_df_top30 <- daa_results_df[order(daa_results_df$p_values),]
  }

  # Database annotation
  if (database == "KEGG") {
    # Use KEGG pathway annotation database to annotate KEGG since pathway_annotation() might meet network issue with pathway = "KO"
    kegg_db <- read.table(keggDB, header=T, check.names=F, row.names=NULL, sep="\t") %>%
      dplyr::mutate(pathway_name = pathway_level3, pathway_map = pathway_level3) %>%
      dplyr::mutate(pathway_class = paste0(pathway_level1, "; ", pathway_level2)) %>%
      dplyr::select(pathway_ID, pathway_name, pathway_class, pathway_map)
    daa_annotated_results_df <- merge(daa_results_df_top30, kegg_db, by.x="feature", by.y="pathway_ID", all.x=TRUE)
  } else {
    # Use pathway_annotation() function to annotate EC and MetaCyc
    daa_annotated_results_df <- pathway_annotation(
      pathway = type,
      daa_results_df = daa_results_df_top30,
      ko_to_kegg = ko_to_kegg_flag
    )
  }

  # Generate ggpicrust2 errorbar plot
  p <- pathway_errorbar(
    abundance = abundance,
    daa_results_df = daa_annotated_results_df %>% dplyr::mutate(p_adjust=round(p_adjust,3)),
    Group = meta_df$group,
    p_values_threshold = 2, # Set to 2 since results dataframe has already been filtered by p-value
    order = order_val,
    select = NULL,
    ko_to_kegg = ko_to_kegg_flag,
    p_value_bar = TRUE,
    colors = NULL,
    x_lab = x_lab_val
  )

  # If all log_2_fold_change equals -Inf (caused by all zero counts in one group), do not show log2_fold_change_bars
  if (sum(!is.finite(p$data[["log_2_fold_change"]])) == nrow(p$data)) {
    p <- pathway_errorbar(
      abundance = abundance,
      daa_results_df = daa_annotated_results_df %>% dplyr::mutate(p_adjust=round(p_adjust,3)),
      Group = meta_df$group,
      p_values_threshold = 2, # Set to 2 since results dataframe has already been filtered by p-value
      order = order_val,
      select = NULL,
      ko_to_kegg = ko_to_kegg_flag,
      p_value_bar = FALSE, # Modify it to FALSE
      colors = NULL,
      x_lab = x_lab_val
    )
  }

  # Calculate log_2_fold_change using pathway_errorbar() (30 features each time)
  if (database == "KEGG") {
    # Use KEGG pathway annotation database to annotate KEGG since pathway_annotation() might meet network issue with pathway = "KO"
    kegg_db <- read.table(keggDB, header=T, check.names=F, row.names=NULL, sep="\t") %>%
      dplyr::mutate(pathway_name = pathway_level3, pathway_map = pathway_level3) %>%
      dplyr::mutate(pathway_class = paste0(pathway_level1, "; ", pathway_level2)) %>%
      dplyr::select(pathway_ID, pathway_name, pathway_class, pathway_map)
    test_table_out <- merge(daa_results_df, kegg_db, by.x="feature", by.y="pathway_ID", all.x=TRUE)
  } else {
    # Use pathway_annotation() function to annotate EC and MetaCyc
    test_table_out <- pathway_annotation(
      pathway = type,
      daa_results_df = daa_results_df,
      ko_to_kegg = ko_to_kegg_flag
    )
  }
  log2_fold_change_df <- data.frame(matrix(ncol = 2, nrow = 0))
  colnames(log2_fold_change_df) <- c("feature", "log_2_fold_change")
  for(i in 1:ceiling(nrow(test_table_out)/30)) {
    if (nrow(test_table_out) < (i*30)) {
      # ensure the last dataframe has more than one row (one row will cause an error in pathway_errorbar())
      test_df <- test_table_out[(30*(i-1)):nrow(test_table_out),]
    } else {
      test_df <- test_table_out[(30*(i-1)+1):(30*i),]
    }
    p_tmp <- pathway_errorbar(
      abundance = abundance,
      daa_results_df = test_df %>% dplyr::mutate(p_adjust=round(p_adjust,3)),
      Group = meta_df$group,
      p_values_threshold = 2, # Set to 2 since results dataframe has already been filtered by p-value
      order = order_val,
      select = NULL,
      ko_to_kegg = ko_to_kegg_flag,
      p_value_bar = FALSE, # Modify it to FALSE
      colors = NULL,
      x_lab = x_lab_val
    )
    log2_fold_change_df <- rbind(log2_fold_change_df, p_tmp$data[,c("feature", "log_2_fold_change")])
  }
  log2_fold_change_df <- log2_fold_change_df[!duplicated(log2_fold_change_df$feature),]
  test_table_out <- merge(x = test_table_out,
                          y = log2_fold_change_df,
                          by = "feature")
  test_table_out$log_2_fold_change[is.infinite(test_table_out$log_2_fold_change)] <- NA

  # Prepare output items
  abundance_out <- abundance[order(row.names(abundance), decreasing=FALSE), ]
  test_table_out <- test_table_out %>%
    dplyr::mutate(p_values = as.numeric(p_values)) %>%
    dplyr::select(columns) %>%
    dplyr::arrange(p_values, p_adjust)
  abundance_out <- abundance_out %>%
    rownames_to_column("feature")

  # Output
  return(list("p"=p, "abundance_df"=abundance_out, "test_df"=test_table_out))
}

