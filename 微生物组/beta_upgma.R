# R script to generate UPGMA tree plot merged with taxonomic composition barplot
# By Yewei on 2024.4.16
# Output: {opts$outdir}/{opts$prefix}.UPGMA.{png,pdf,tre}

library(optparse)
library(dplyr)
library(ggplot2)
library(glue)
library(reshape2)
library(RColorBrewer)
library(ggtree)
library(treeio)
library(aplot)

# Parse arguments
if (TRUE){
  option_list = list(
    make_option(c("-i", "--input"), type="character", default=NULL,
                help="Newick UPGMA tree generated by qiime diversity beta_rarefaction"),
    make_option(c("-l", "--level"), type="character", default=NULL,
                help="Taxonomic level (Kingdom, Phylum, Class, Order, Family, Genus, Species)"),
    make_option(c("-b", "--abundance"), type="character", default=NULL,
                help="Abundance table of selected taxonomic level "),
    make_option(c("-m", "--metadata"), type="character", default=NULL,
                help="Metadata file for all samples"),
    make_option(c("-n", "--group"), type="character", default="group",
                help="Group variable name in metadata [default %default]"),
    make_option(c("-s", "--sample"), type="character", default="sample",
                help="Sample variable name in metadata [default %default]"),
    make_option(c("-o", "--outdir"), type="character", default=".",
                help="Output directory [default %default]"),
    make_option(c("-p", "--prefix"), type="character", default="output",
                help="Output file name prefix [default %default]"),
    make_option(c("-t", "--topn"), type="integer", default=10,
                help="Top N items with highest abundance to present [default %default]"),
    make_option(c("-c", "--contrast"), type="character", default="A-vs-B",
                help="Display samples in contrast groups (e.g. 'A-vs-B') [default %default]"),
    make_option(c("-d", "--dist"), type="character", default="braycurtis",
                help="Beta distance type for PCoA and NMDS (braycurtis, jaccard, weighted_unifrac, unweighted_unifrac) [default %default]"),
    make_option(c("-x", "--space"), type="double", default=0.01,
                help="Space for sample names (slightly increase this value for long sample names, e.g. 0.02 or 0.03) [default %default]"),
    make_option(c("-e", "--others"), type="logical", action="store_true", default=FALSE,
                help="If there is an 'Others' row other than Top N items to present [default %default]"),
    make_option(c("-u", "--unassigned"), type="logical", action="store_true", default=FALSE,
                help="If there is an 'Unassigned' row to present [default %default]"),
    make_option(c("-f", "--font"), type="integer", default=4,
                help="Font size for sample names [default %default]"),
    make_option(c("-w", "--plot_width"), type="numeric", default=20,
                help="Plot width [default %default]"),
    make_option(c("-g", "--plot_height"), type="numeric", default=10,
                help="Plot height [default %default]")
  )
  opts = parse_args(OptionParser(option_list=option_list))
}

# Main

# Read newick format tree file
tree <- read.newick(opts$input)

# Read contrast groups
group_list <- unlist(strsplit(opts$contrast, "-vs-"))

# Reads meta data
meta_df <- read.table(opts$meta, header=T, check.names=F, row.names=NULL, sep="\t") %>%
  dplyr::rename(sample=opts$sample, group=opts$group) %>%
  dplyr::select(sample, group)
meta_df$group <- factor(meta_df$group, levels=group_list)

# Samples not in contrast group
samples_to_drop <- meta_df[!meta_df$group %in% group_list, "sample"]

# Filter tree file and output
tree_filter <- drop.tip(tree, samples_to_drop)
write.tree(tree_filter, file=glue("{opts$outdir}/{opts$prefix}.UPGMA.tre"))

# Plot
# Beta distance type
if (opts$dist == "braycurtis") {
  dist_type <- "Bray-Curtis Distance"
} else if (opts$dist == "jaccard") {
  dist_type <- "Jaccard Distance"
} else if (opts$dist == "weighted_unifrac") {
  dist_type <- "Weighted UniFrac Distance"
} else if (opts$dist == "unweighted_unifrac") {
  dist_type <- "Unweighted UniFrac Distance"
}

# Tree plot
tree_plot <- groupOTU(tree_filter, split(meta_df$sample, meta_df$group))
p <- ggtree(tree_plot, branch.length='none') +
  geom_tiplab(aes(color=group), fontface=2, size=opts$font) +
  hexpand(opts$space) +
  scale_color_brewer(palette="Set1", 
                     breaks=group_list, 
                     labels=group_list) +
  labs(title=glue("UPGMA - {dist_type}"),
       color="Group") +
  theme(legend.title=element_text(face="bold"),
        legend.position='bottom',
        legend.justification='center',
        plot.title=element_text(hjust=0.5, face="bold"))

# Taxonomic composition barplot
# Read taxonomic abundance table
abundance_df <- read.table(opts$abundance, header=T, check.names=F, sep="\t", quote="") %>%
  dplyr::select(-c(Taxonomy, samples_to_drop))

# Sort taxonomic abundance table
abundance_sort_df <- abundance_df[order(rowMeans(abundance_df[, 2:length(colnames(abundance_df))]), decreasing = T),]

if (opts$unassigned) {
  if (nrow(abundance_sort_df) - 1 >= opts$topn) {
    abundance_top_df <- abundance_sort_df[abundance_sort_df[,1]!="Unassigned",][1:opts$topn,]
  } else {
    abundance_top_df <- abundance_sort_df[abundance_sort_df[,1]!="Unassigned",]
  }

  if (opts$others) {
    others_line <- c("Others", as.vector(1 - colSums(abundance_sort_df[abundance_sort_df[,1]!="Unassigned",][1:opts$topn,][, 2:ncol(abundance_sort_df)])))
    abundance_top_df <- rbind(abundance_top_df, others_line)
  }

  abundance_top_df <- rbind(abundance_top_df, abundance_sort_df[abundance_sort_df[,1]=="Unassigned",])
} else {
  if (nrow(abundance_sort_df) >= opts$topn) {
    abundance_top_df <- abundance_sort_df[1:opts$topn,]
  } else {
    abundance_top_df <- abundance_sort_df
  }

  if (opts$others) {
    others_line <- c("Others", as.vector(1 - colSums(abundance_top_df[, 2:ncol(abundance_sort_df)])))
    abundance_top_df <- rbind(abundance_top_df, others_line)
  }
}

abundance_top_long_df <- melt(abundance_top_df, id.vars=opts$level) %>%
  rename(sample = variable, level=opts$level)
abundance_top_long_df$value <- as.numeric(abundance_top_long_df$value)
abundance_top_long_df$level <- factor(abundance_top_long_df$level , levels=abundance_top_df[,1])

# Generate taxonomic composition barplot
bar <- abundance_top_long_df %>% ggplot(aes(sample, value, fill=level)) +
  geom_bar(stat="identity", position=position_fill(reverse=TRUE), width=0.9) +
  labs(title="Taxonomic Composition", x="", y="", fill=opts$level) +
  theme_minimal() +
  theme(axis.title.x=element_blank(),
        axis.line.x=element_line(linewidth=0.5),
        axis.ticks.x=element_line(linewidth=0.5),
        axis.ticks.length.x=unit(0.25, "cm"),
        axis.text.y=element_blank(),
        axis.ticks.y=element_blank(),
        panel.grid.minor=element_blank(),
        panel.grid.major=element_blank(),
        legend.title=element_text(face="bold"),
        plot.title=element_text(hjust=0.5, face="bold")) +
  scale_fill_brewer(palette="Paired") +
  scale_y_continuous(expand=c(0, 0)) +
  coord_flip()

options("aplot_guides" = "keep")
p_out <- bar %>% insert_left(p, width=.8)
ggsave(filename = file.path(opts$outdir, glue("{opts$prefix}.UPGMA.png")),
       device = "png",
       plot = p_out,
       width = opts$plot_width,
       height = opts$plot_height)
ggsave(filename = file.path(opts$outdir, glue("{opts$prefix}.UPGMA.pdf")),
       device = "pdf",
       plot = p_out,
       width = opts$plot_width,
       height = opts$plot_height)